#!/usr/bin/env node
// Renders the generated operation reference inside docs/agent-api.md from the live registry.
//   node scripts/agent-docs.mjs --write   regenerate the block between the markers
//   node scripts/agent-docs.mjs --check   exit 1 when the committed block is stale (CI gate)
import { readFile, writeFile } from 'node:fs/promises';
import { fileURLToPath, pathToFileURL } from 'node:url';
import { createAgentOperations, OPERATIONS_VERSION } from '../server/agent-ops.mjs';

const DOC = fileURLToPath(new URL('../docs/agent-api.md', import.meta.url));
const START = '<!-- agent-ops:start -->';
const END = '<!-- agent-ops:end -->';

const typeLabel = (schema = {}) => {
  if (schema.enum) return schema.enum.map((value) => `\`${value}\``).join(' \\| ');
  if (schema.const !== undefined) return `\`${JSON.stringify(schema.const)}\``;
  const type = Array.isArray(schema.type) ? schema.type.join(' \\| ') : schema.type || 'any';
  if (type === 'array') return `array<${typeLabel(schema.items).replace(/`/g, '')}>`;
  const bounds = [schema.minimum !== undefined && `≥${schema.minimum}`, schema.maximum !== undefined && `≤${schema.maximum}`, schema.maxLength !== undefined && `≤${schema.maxLength} chars`].filter(Boolean).join(', ');
  return bounds ? `${type} (${bounds})` : type;
};
const cell = (value) => String(value ?? '').replace(/\|/g, '\\|').replace(/\n+/g, ' ');
const propertyTable = (schema) => {
  const entries = Object.entries(schema.properties || {});
  if (!entries.length) return '_No arguments._\n';
  const required = new Set(schema.required || []);
  return `| Field | Type | Required | Notes |\n| --- | --- | --- | --- |\n${entries.map(([name, property]) => `| \`${name}\` | ${cell(typeLabel(property))} | ${required.has(name) ? 'yes' : ''} | ${cell(property.description)} |`).join('\n')}\n`;
};

export function renderReference() {
  const catalog = createAgentOperations({}).catalog();
  const behavior = (annotations) => [annotations.readOnlyHint ? 'read-only' : annotations.destructiveHint ? 'writes (may remove or replace data)' : 'writes (additive)', annotations.idempotentHint ? 'idempotent' : null, annotations.openWorldHint ? 'contacts external services' : 'local only'].filter(Boolean).join(' · ');
  const summary = `| Operation | Behavior | Summary |\n| --- | --- | --- |\n${catalog.map((operation) => `| [\`${operation.name}\`](#${operation.name.replace(/_/g, '_')}) | ${behavior(operation.annotations)} | ${cell(operation.title)} |`).join('\n')}\n`;
  const sections = catalog.map((operation) => `### ${operation.name}\n\n**${operation.title}** — ${behavior(operation.annotations)}\n\n${operation.description}\n\n${propertyTable(operation.inputSchema)}\nReturns: ${Object.keys(operation.outputSchema.properties || {}).map((key) => `\`${key}\``).join(', ')}\n`).join('\n');
  return `${START}\n<!-- Generated by scripts/agent-docs.mjs from server/agent-ops.mjs (operations ${OPERATIONS_VERSION}). Do not edit by hand. -->\n\n${summary}\n${sections}\n${END}`;
}

async function main() {
  const mode = process.argv[2];
  if (!['--write', '--check'].includes(mode)) { process.stderr.write('Usage: agent-docs.mjs --write | --check\n'); process.exit(2); }
  const document = await readFile(DOC, 'utf8');
  const start = document.indexOf(START), end = document.indexOf(END);
  if (start < 0 || end < start) { process.stderr.write(`docs/agent-api.md must contain ${START} and ${END}\n`); process.exit(2); }
  const next = `${document.slice(0, start)}${renderReference()}${document.slice(end + END.length)}`;
  if (mode === '--check') {
    if (next.replace(/\r\n/g, '\n') !== document.replace(/\r\n/g, '\n')) { process.stderr.write('docs/agent-api.md reference is stale: run node scripts/agent-docs.mjs --write\n'); process.exit(1); }
    process.stdout.write('docs/agent-api.md reference is current\n');
    return;
  }
  await writeFile(DOC, next);
  process.stdout.write('docs/agent-api.md reference regenerated\n');
}

if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) main().catch((error) => { process.stderr.write(`${error.message}\n`); process.exit(1); });
